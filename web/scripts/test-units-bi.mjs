import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createServer } from 'vite';
const require = createRequire(import.meta.url);
const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const seed = structuredClone(require('../../backend/src/data/goalsWorkbookSeed.json'));
const identities = new Map();
Object.values(seed.months).forEach(month => month.stores.forEach(store => { store.storeId = `db_${store.id}`; identities.set(store.storeId, { id: store.storeId, name: store.name, active: 1 }); }));
seed.registeredStores = [...identities.values()];
const server = await createServer({ root: webDir, server: { middlewareMode: true }, appType: 'custom' });
try {
  const { buildUnitsBi } = await server.ssrLoadModule('/src/modules/unitsManagement/utils/unitsBiCalculations.ts');
  const base = { history: seed, period: '2026-01', latestPeriod: '2026-10', plans: [], closings: [] };
  const january = buildUnitsBi(base);
  assert.equal(january.sales, 1835132, 'O faturamento de janeiro deve vir do histórico real, não de listas vazias.');
  assert.equal(january.salesCoverage, 19);
  assert.equal(january.comparison.find(row => row.year === 2025).total, 1092798);
  assert.equal(january.rows.find(row => row.name === 'IRATI CENTRO').sales, 143682);
  assert.equal(january.rows.find(row => row.name === 'IRATI CENTRO').goal, 111778.92);
  const saved = buildUnitsBi({ ...base, plans: [{ storeId: 'db_irati_centro', amount: 200000, version: 1 }] });
  assert.equal(saved.rows.find(row => row.name === 'IRATI CENTRO').goal, 200000, 'Meta salva deve prevalecer sobre sugestão.');
  const zeroGoal = buildUnitsBi({ ...base, plans: [{ storeId: 'db_irati_centro', amount: 0, version: 1 }] });
  assert.equal(zeroGoal.rows.find(row => row.name === 'IRATI CENTRO').goal, 0);
  assert.equal(zeroGoal.rows.find(row => row.name === 'IRATI CENTRO').achievement, null, 'Meta zero não deve gerar infinito.');
  const old = buildUnitsBi({ ...base, period: '2025-01' });
  assert.equal(old.sales, 1092798, 'Alterar ano deve mudar o faturamento.');
  const november = buildUnitsBi({ ...base, period: '2026-11' });
  assert.equal(november.sales, null, 'Ausência de informação não é faturamento zero.');
  assert.ok(november.comparison.find(row => row.year === 2025).total > 0, 'Mesmo sem novembro/2026, os anos anteriores devem aparecer.');
  assert.equal(november.daily.length, 0, 'Não distribuir os totais mensais artificialmente nos dias.');
  assert.ok(november.payments.every(row => row.percent === null));
  const closing = { storeId: 'db_irati_centro', closingDate: '2026-11-01', salesCents: 10000, salesCount: 10,
    cashCents: 4000, pixKaisCents: 6000, pixStoneCents: 0, pixCnpjCents: 0, debitCents: 0, creditCents: 0 };
  const withClosing = buildUnitsBi({ ...base, period: '2026-11', closings: [closing] });
  assert.equal(withClosing.sales, 100);
  assert.equal(withClosing.salesCoverage, 1);
  assert.equal(withClosing.daily[0].accumulated, 100);
  assert.equal(withClosing.payments.find(row => row.key === 'cashCents').percent, 40);
  const overlapping = buildUnitsBi({ ...base, closings: [{ ...closing, closingDate: '2026-01-01' }] });
  assert.equal(overlapping.sales, 1835132, 'Não duplicar faturamento já registrado no histórico mensal.');
  const wrongPeriod = buildUnitsBi({ ...base, closings: [closing] });
  assert.equal(wrongPeriod.closingCount, 0);
  assert.equal(buildUnitsBi({ ...base, period: '2024-11' }).rows.find(row => row.name === 'CAMPO LARGO').profitValue, null, 'Unidade sem operação não gera prejuízo artificial.');
  assert.equal(january.annual.length, 12);
  assert.equal(january.annual[10].total, null);
  assert.ok(january.rows.every(row => row.achievement === null || Number.isFinite(row.achievement)));
  console.log('BI: histórico multianual, filtros mensais, metas salvas, cobertura, ausência de informação, prejuízos, pagamentos e prevenção de duplicação verificados.');
} finally { await server.close(); }
